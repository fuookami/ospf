//! 仅编排既有 Gantt 列生成循环和恢复记录提取，不内建第二套主模型。 / Orchestrate the existing Gantt column-generation loop and recovery extraction without a second master model.

use std::sync::Arc;
use ospf_rust_core::model::MetaModel;
use ospf_rust_core::solver::{SolveDiagnostics, SolveReport, SolveSolution, SolveStatistics, SolveWarning};
use ospf_rust_framework::solver::column_generation_solver::ColumnGenerationSolver;
use ospf_rust_framework_gantt_scheduling::{GanttError, GanttResult};
use ospf_rust_framework_gantt_scheduling::application::algorithm::{BunchBranchAndPriceAlgorithm, ColumnGenerationPolicy};
use ospf_rust_framework_gantt_scheduling::domain::common::BunchId;
use ospf_rust_framework_network_scheduling::domain::path::PathSearchBudget;
use crate::framework::demo4::domain::bunch_compilation::context::{BunchCompilationContext, RecoverySchedule};
use crate::framework::demo4::domain::bunch_generation::pricing::{RecoveryPricingPolicy, RecoveryPricingResult};
use crate::framework::demo4::domain::bunch_generation::problem::RecoveryProblem;
use crate::framework::demo4::domain::bunch_generation::recovery::RecoveryBunchCandidate;
use crate::framework::demo4::domain::bunch_generation::initial::{RecoveryInitialBunchGenerator, RecoveryInitialConfiguration, RecoveryInitialGenerationResult};
use crate::framework::demo4::domain::rule::service::RecoveryCostPolicy;

/// 本次 Gantt 应用配置；初始列必须保留完整恢复记录。 / Gantt application configuration with complete recovery records for initial columns.
#[derive(Debug, Clone, Default)]
pub struct RecoveryApplicationConfiguration {
    /// 可选的可行初始列；不以嵌套全局求解生成。 / Optional feasible initial columns, never generated by a nested global solve.
    pub initial: Vec<RecoveryBunchCandidate>,
    /// 可选自动初始列策略；与显式列合并，不启动第二次全局求解。 / Optional automatic initial-column strategy, merged with explicit columns without a second global solve.
    pub initial_generation: Option<RecoveryInitialConfiguration>,
    /// Gantt 原有循环配置。 / Existing Gantt loop configuration.
    pub column_generation: ColumnGenerationPolicy,
    /// 每轮每飞机的路径标签预算。 / Per-round, per-aircraft path label budget.
    pub maximum_labels: Option<usize>,
}

/// 生产校验后的恢复调度及有限候选和定价证据边界。 / Production-validated recovery schedule with finite candidates and pricing-evidence boundaries.
#[derive(Debug, Clone)]
pub struct RecoverySolution {
    /// 保留实际恢复记录的选中调度。 / Selected schedule retaining actual recovery records.
    pub schedule: RecoverySchedule,
    /// 最终活跃候选 ID；有限主问题最优仅覆盖该集合。 / Final active candidate IDs; finite-master optimality covers only this set.
    pub candidate_ids: Vec<BunchId>,
    /// 每轮共享路径状态、完成度及完整 reduced cost。 / Per-round shared-path states, completion and complete reduced costs.
    pub pricing: Vec<RecoveryPricingResult>,
    /// 最终有限主问题数值报告，不提升为全局整数证明。 / Final finite-master numeric report, never promoted to a global integer proof.
    pub finite_master_report: SolveReport<f64>,
    /// 自动初始列的完整作用域和搜索诊断。 / Complete scopes and search diagnostics for automatic initial columns.
    pub initial_generation: Option<RecoveryInitialGenerationResult>,
}

/// 单次应用求解入口，每次创建新的 Gantt context、policy 和主模型。 / Single-use application solve creating fresh Gantt context, policy and master on every call.
pub struct RecoveryApplicationService<S> {
    solver: S,
}

impl<S: ColumnGenerationSolver> RecoveryApplicationService<S> {
    /// 注入求解后端。 / Inject the solver backend.
    pub fn new(solver: S) -> Self { Self { solver } }

    /// 从初始列到 RMP、路径定价、增列和最终 MILP 全部复用 Gantt 循环。 / Reuse the Gantt loop for initial columns, RMP, path pricing, column insertion and final MILP.
    pub fn solve<C>(
        self,
        problem: Arc<RecoveryProblem<C>>,
        configuration: RecoveryApplicationConfiguration,
    ) -> GanttResult<SolveReport<RecoverySolution>>
    where
        C: RecoveryCostPolicy + Send + Sync + 'static,
    {
        let mut context = BunchCompilationContext::with_resolver(problem.configuration().clone(), problem.clone())?;
        let mut model = MetaModel::new("demo4-recovery");
        context.register(&mut model)?;
        let initial_generation = configuration.initial_generation.as_ref().map(|initial| RecoveryInitialBunchGenerator.generate(
            &problem, initial, &PathSearchBudget { maximum_labels: configuration.maximum_labels, ..Default::default() },
        )).transpose()?;
        let mut initial = configuration.initial;
        if let Some(generated) = &initial_generation { initial.extend(generated.batch.columns.clone()); }
        context.add_candidates(0, initial, &mut model)?;
        let policy = RecoveryPricingPolicy::new(problem.clone(), configuration.maximum_labels);
        let executors = problem.configuration().aircraft.iter().map(|aircraft| aircraft.reg_no.0.clone()).collect::<Vec<_>>();
        let mut algorithm = BunchBranchAndPriceAlgorithm::new(context, self.solver, policy, executors, configuration.column_generation);
        let report = algorithm.run_report(&mut model)?;
        let domain = if let Some(incumbent) = &report.solution {
            let schedule = algorithm.context.extract_solution(&model, &incumbent.values)?;
            let candidate_ids = algorithm.context.master().compilation.base.aggregation.bunches().iter().map(|entry| entry.id.clone()).collect();
            Some(RecoverySolution { schedule, candidate_ids, pricing: algorithm.policy.history()?, finite_master_report: report.clone(), initial_generation: initial_generation.clone() })
        } else { None };
        let mut projected = project(report, domain)?;
        if let Some(generated) = initial_generation {
            projected.diagnostics.extensions.insert("demo4.initialGenerationCompletion".into(), format!("{:?}", generated.batch.completion));
            projected.diagnostics.extensions.insert("demo4.initialGenerationColumns".into(), generated.batch.columns.len().to_string());
        }
        Ok(projected)
    }
}

fn project(report: SolveReport<f64>, domain: Option<RecoverySolution>) -> GanttResult<SolveReport<RecoverySolution>> {
    let mut statistics = SolveStatistics { solve_time: report.statistics.solve_time, iterations: report.statistics.iterations,
        nodes: report.statistics.nodes, solution_count: report.statistics.solution_count,
        extensions: report.statistics.extensions.clone(), ..Default::default() };
    statistics.extensions.insert("demo4.proofScope".into(), "finite-candidates-only".into());
    let diagnostics = SolveDiagnostics { issues: report.diagnostics.issues.clone(), warnings: report.diagnostics.warnings.clone(),
        extensions: report.diagnostics.extensions.clone(), ..Default::default() };
    // 有限候选不可行不代表完整路径域不可行；真实无 incumbent 原因保留在终止原因及扩展中。 / Finite-candidate infeasibility does not prove full-path infeasibility; retain actual no-incumbent reasons in termination and extensions.
    let status = if domain.is_some() { ospf_rust_core::solver::ProblemStatus::Feasible } else { ospf_rust_core::solver::ProblemStatus::Unknown };
    let mut builder = SolveReport::builder(status, report.termination_reason).statistics(statistics).diagnostics(diagnostics)
        .provenance(report.provenance.clone()).trace(report.trace.clone())
        .warning(SolveWarning::new("FiniteRecoveryMaster", "仅当前候选主问题，未声明全局整数最优 / current candidate master only; global integer optimality is not claimed"));
    if let Some(domain) = domain {
        let objective = report.solution.as_ref().and_then(|solution| solution.objective_value.or(solution.objective));
        let mut solution = SolveSolution::incumbent(domain);
        solution.objective_value = objective;
        builder = builder.solution(solution);
    }
    let mut projected = builder.build().map_err(invalid)?;
    projected.diagnostics.extensions.insert("demo4.finiteMasterStatus".into(), format!("{:?}", report.problem_status));
    for warning in report.warnings { projected.warnings.push(warning); }
    Ok(projected)
}

fn invalid(error: impl std::fmt::Display) -> GanttError {
    GanttError::Calculation { message: format!("恢复应用合同失败 / recovery application contract failed: {error}") }
}
